"""Whole-floor episodes of the token sampler (EXPERIMENTS.md C57 on): the worker of TokSamplerConfig.mode 'floor'.

A worker's root instance resets real Basement I floors (the bridge's reset_mode 'floor': a fresh run's own start,
3 red hearts, 1 bomb, the floor of the seed; floors with Labyrinth, Lost or Maze skipped) and a template clone is
parked at each floor's start, as in tok_sampler. An episode is a lean clone that plays on through the doors until the
player dies, the level's stage changes (the trapdoor after the boss: the floor is cleared), the time limit, or
cfg.floor_stall_seconds without a new room or a cleared one. Protocol, records and the one-decision action lag are
tok_sampler's; a step during which the room changes ends at the new room's first logic frame (the bridge's rule).

Start-state archive: an episode that enters a room for the first time is cloned there with probability
cfg.snapshot_prob, and the parked clone joins the worker's archive (cfg.archive_size entries; the most used one makes
room). cfg.archive_prob of the episodes start from an archive entry instead of the floor's start: a clone of it,
reseeded, so the same room entry is played with other random draws. Rooms deep in a floor (the boss) are then
practised as often as the first ones, without playing the way there each time. Evaluation uses no archive: every
seed's floor once, from its start.

Runs (cfg.mode 'run', 2026-10-06): the same worker; the stage change is an event (EV_EXIT) and the episode goes on on
the next floor (until death, cfg.run_seconds, or a floor's own stall rule); the first room of every later floor is
always parked in the archive (an archive entry's info['stage0'] is its floor's stage), so later floors are practised
from there as the room entries of Basement I are. Floors are generated by the game as they come (any curse, also
Labyrinth / Lost / Maze, which the Basement I reset skips; under Lost the bridge sends an empty map block with items
on, lean_items).

Counterfactual branches (cfg.branch_share > 0, 2026-10-07; tok_branch.py has the definitions): every room change is
cloned as with the teacher (the restore points), branch points are detected in the record stream (detect), queued
(PointQueue) and run between episodes within cfg.branch_share of the worker's wall time (run_point: restore, the
options' prefixes, the reseed, branch episodes driven by the trainer's actions), and each processed point leaves a
choice record in the worker's ring. With branch_share 0 nothing of this runs and the worker is as before.

Hindsight search teacher (cfg.teacher): with it every room change is cloned, and a hurt is restored from the clone of
the room it happened in (the bridge's play command ends at a room change, so a restore never crosses one). The parked
clones are shared by the archive, the running episode and queued searches through a reference count.
"""

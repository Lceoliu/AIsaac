def row_digest(row):
    """Phase B2 (the twin check): crc32 of what the policy sees in a record (ROW of one), the entity and door lists cut
    to their counts (a slot's stale entries beyond them are not part of the state), and the step's reward fields."""
    r = row[0]
    ne, nd = int(r['n_ent']), int(r['n_doors'])
    parts = [r['player'], r['ent'][:ne], r['ent_id'][:ne], r['ent_item'][:ne], r['doors'][:nd], r['patch'],
             r['grid'], r['map'], r['inv'], r['pitem'], r['pinv'], r['pcharge'],
             np.array([r['bombs'], r['events'], r['done'], r['stage']], np.int64),
             np.array([r['hurt'], r['damage']], np.float64)]
    c = 0
    for a in parts:
        c = zlib.crc32(np.ascontiguousarray(a).tobytes(), c)
    return c


class Parked:
    """A parked clone and what an episode started from it must know; closed when its last holder lets go."""
    live = set()   # the Parked objects of this worker whose clone is open (diagnostic: the role dumps)

    def __init__(self, clone, **info):
        self.clone, self.refs, self.info = clone, 1, info
        Parked.live.add(self)

    def hold(self):
        self.refs += 1
        return self

    def release(self):
        self.refs -= 1
        if self.refs <= 0 and self.clone is not None:
            try:
                self.clone.close()
            except OSError:
                pass
            self.clone = None
            Parked.live.discard(self)

    @property
    def pid(self):
        return getattr(self.clone, 'pid', None) if self.clone is not None else None



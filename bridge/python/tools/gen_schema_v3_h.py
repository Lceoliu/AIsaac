"""Generate engine/abp_schema_v3.h from isaac_bridge/schema_v3.py (the single source of truth of visible-v3).

  python tools/gen_schema_v3_h.py            (from bridge/python: writes ../engine/abp_schema_v3.h)
  python tools/gen_schema_v3_h.py --check    (exit 1 if the committed header differs)

tests/test_schema_v3.py asserts the committed header equals generate(). Never edit the header by hand."""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
from isaac_bridge import schema_v3 as S   # noqa: E402

OUT = HERE.parent.parent / 'engine' / 'abp_schema_v3.h'
CRLF, LF = chr(13) + chr(10), chr(10)   # (a Windows checkout may hold the header with CRLF)


def _ident(name):
    return re.sub(r'[^A-Za-z0-9]', '_', name).upper()


def _columns(prefix, cols):
    """Named columns one define each; a numbered block (curse0..31, tear_w0..7, ...) as _FIRST / _N."""
    out, i = [], 0
    while i < len(cols):
        name, kind = cols[i][0], cols[i][1]
        if kind == 'reserved':
            i += 1
            continue
        m = re.fullmatch(r'(.*?)(\d+)', name)
        if m and m.group(2) == '0':
            j = i
            while j < len(cols) and cols[j][0] == f'{m.group(1)}{j - i}':
                j += 1
            base = _ident(m.group(1).rstrip('_'))
            out.append(f'#define ABP_V3_{prefix}_{base}_FIRST {i}')
            out.append(f'#define ABP_V3_{prefix}_{base}_N {j - i}')
            i = j
            continue
        note = f'{kind}: {cols[i][2]}'.replace('*/', '* /')
        out.append(f'#define ABP_V3_{prefix}_{_ident(name)} {i}   /* {note} */')
        i += 1
    return out


def _bits(prefix, fields):
    out, shift = [], 0
    for name, bits in fields:
        out.append(f'#define ABP_V3_{prefix}_{_ident(name)}_SHIFT {shift}')
        out.append(f'#define ABP_V3_{prefix}_{_ident(name)}_BITS {bits}')
        shift += bits
    out.append(f'#define ABP_V3_{prefix}_TOTAL_BITS {shift}')
    return out


def generate():
    L = ['/* abp_schema_v3.h: visible-v3 constants, GENERATED by bridge/python/tools/gen_schema_v3_h.py from',
         ' * bridge/python/isaac_bridge/schema_v3.py (the single source of truth: DESIGN.md F1 / F2 / F4). Do not edit;',
         ' * tests/test_schema_v3.py checks this file against the generator. */',
         '#ifndef ABP_SCHEMA_V3_H', '#define ABP_SCHEMA_V3_H', '',
         '/* ---- F1: identity and header */',
         f'#define ABP_V3_SCHEMA "{S.SCHEMA}"', f'#define ABP_V3_VERSION {S.VERSION}',
         f'#define ABP_V3_FRAME_BYTES {S.FRAME_BYTES}', f'#define ABP_V3_MAGIC {S.MAGIC}',
         f'#define ABP_V3_LAYOUT_GEN {S.LAYOUT_GEN}', f'#define ABP_V3_HEADER {S.HEADER}']
    for k in ('H_MAGIC', 'H_SIZE', 'H_P', 'H_E', 'H_N', 'H_S', 'H_GEN', 'H_PRODUCER'):
        L.append(f'#define ABP_V3_{k} {getattr(S, k)}')
    for k, v in S.PRODUCER.items():
        L.append(f'#define ABP_V3_PRODUCER_{_ident(k)} {v}')
    L += ['', '/* ---- F1: room canvas (per cell: word 0 bits, word 1 bits, grid type, variant, state) */',
          f'#define ABP_V3_CANVAS_H {S.CANVAS_H}', f'#define ABP_V3_CANVAS_W {S.CANVAS_W}',
          f'#define ABP_V3_ROOM_WORDS {S.ROOM_WORDS}', f'#define ABP_V3_RC {S.RC}']
    L += _bits('W0', S.ROOM_W0) + _bits('W1', S.ROOM_W1)
    L += [f'#define ABP_V3_LOCAL_SIDE {S.LOCAL_SIDE}', f'#define ABP_V3_LOCAL {S.LOCAL}',
          '', '/* ---- F1: minimap (one float per cell) */', f'#define ABP_V3_MAP_SIDE {S.MAP_SIDE}',
          f'#define ABP_V3_MAP_ICONS {S.MAP_ICONS}']
    L += _bits('MAP', S.MAP_BITS)
    L += ['', '/* ---- F1: sizes */', f'#define ABP_V3_FIXED {S.FIXED}', f'#define ABP_V3_PF {S.PF}',
          f'#define ABP_V3_EF {S.EF}', f'#define ABP_V3_NF {S.NF}', f'#define ABP_V3_SF {S.SF}',
          f'#define ABP_V3_BODY {S.BODY}', f'#define ABP_V3_CAP_ENTITY {S.CAP_ENTITY}',
          '/* frame floats = ABP_V3_FIXED + p * ABP_V3_BODY + e * ABP_V3_EF + n * ABP_V3_NF + s * ABP_V3_SF */',
          '', '/* ---- F1: columns (raw units on the wire; reserved columns 0) */']
    for prefix, cols in (('P', S.P_COLS), ('E', S.E_COLS), ('N', S.N_COLS), ('S', S.S_COLS)):
        L += _columns(prefix, cols)
    L += ['', '/* ---- F1: embedding tables and namespaces */',
          f'#define ABP_V3_IDENTITY_ROWS {S.IDENTITY_ROWS}', f'#define ABP_V3_IDENTITY_UNKNOWN {S.IDENTITY_UNKNOWN}',
          f'#define ABP_V3_ITEM_ROWS {S.ITEM_ROWS}', f'#define ABP_V3_ITEM_UNKNOWN {S.ITEM_UNKNOWN}',
          f'#define ABP_V3_CAT_ROWS {S.CAT_ROWS}', f'#define ABP_V3_ANIM_ROWS {S.ANIM_ROWS}']
    for k, (b, n) in S.ITEM_NS.items():
        L += [f'#define ABP_V3_ITEM_NS_{_ident(k)}_BASE {b}', f'#define ABP_V3_ITEM_NS_{_ident(k)}_SIZE {n}']
    for k, (b, n) in S.CAT_NS.items():
        L += [f'#define ABP_V3_CAT_NS_{_ident(k)}_BASE {b}', f'#define ABP_V3_CAT_NS_{_ident(k)}_SIZE {n}']
    for name, table in (('GAME_VERSION', S.GAME_VERSION), ('BODY_ROLE', S.BODY_ROLE), ('SLOT_FAMILY', S.SLOT_FAMILY),
                        ('ENTITY_KIND', S.ENTITY_KIND)):
        L += [f'#define ABP_V3_{name}_{_ident(k)} {v}' for k, v in table.items()]
    L += ['', '/* ---- F1: flags (16-bit words) */', f'#define ABP_V3_FLAG_WORD_BITS {S.FLAG_WORD_BITS}',
          f'#define ABP_V3_TEAR_WORDS {S.TEAR_WORDS}', f'#define ABP_V3_PROJ_WORDS {S.PROJ_WORDS}',
          f'#define ABP_V3_EFLAG_WORDS {S.EFLAG_WORDS}',
          f'#define ABP_V3_PROJ_VISIBLE_MASK 0x{S.PROJ_VISIBLE_MASK:016x}ULL',
          f'#define ABP_V3_ENTITY_VISIBLE_MASK 0x{S.ENTITY_VISIBLE_MASK:016x}ULL',
          f'#define ABP_V3_TEAR_AB_BITS {len(S.TEAR_AB_TO_CANON)}',
          '/* AB+ TearFlags bit b -> canonical (Rep TEARFLAG) bit */',
          'static const unsigned char abp_v3_tear_ab_to_canon[ABP_V3_TEAR_AB_BITS] = {',
          '    ' + ', '.join(str(S.TEAR_AB_TO_CANON[b]) for b in range(len(S.TEAR_AB_TO_CANON))) + '};',
          '', '/* ---- F2: actions */', f'#define ABP_V3_N_HEADS {S.N_HEADS}', f'#define ABP_V3_N_LOGITS {S.N_LOGITS}',
          f'#define ABP_V3_CRN_COLS {S.CRN_COLS}', f'#define ABP_V3_N_ACTION_CODES {S.N_ACTION_CODES}',
          'static const int abp_v3_head_sizes[ABP_V3_N_HEADS] = {' + ', '.join(map(str, S.HEAD_SIZES)) + '};',
          'static const int abp_v3_action_code_mul[ABP_V3_N_HEADS] = {'
          + ', '.join(map(str, S.ACTION_CODE_MUL)) + '};']
    L += [f'#define ABP_V3_HEAD_{_ident(h)} {i}' for i, h in enumerate(S.HEADS)]
    L += [f'#define ABP_V3_BUTTON_ABP_{k} {v}' for k, v in S.BUTTON_ACTION_ABP.items()]
    L += [f'#define ABP_V3_STEP_LINE_FIELDS {len(S.STEP_LINE_FIELDS)}   /* S {" ".join(S.STEP_LINE_FIELDS)} */',
          '', '/* ---- F4: records */', f'#define ABP_V3_ACTION_F {S.ACTION_F}',
          f'#define ABP_V3_V2_META {S.V2_META}', f'#define ABP_V3_TEACH_META {S.TEACH_META}']
    L += [f'#define ABP_V3_V2_{_ident(k)} {i}' for i, k in enumerate(S.V2_FIELDS)]
    L += [f'#define ABP_V3_TEACH_{_ident(k)} {i}' for i, k in enumerate(S.TEACH_FIELDS)]
    L += ['', '#endif', '']
    return '\n'.join(L)


if __name__ == '__main__':
    text = generate()
    if '--check' in sys.argv:
        ok = OUT.exists() and OUT.read_bytes().decode().replace(CRLF, LF) == text
        print('abp_schema_v3.h', 'up to date' if ok else 'DIFFERS from the generator')
        sys.exit(0 if ok else 1)
    OUT.write_bytes(text.encode())
    print('wrote', OUT)
